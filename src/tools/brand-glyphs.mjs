// Converts the wordmark «mrlololi» (Bricolage Grotesque 800) and the two taglines (EB Garamond
// italic 500) into outlines: src/templates/brand-glyphs.json. The logo never needs a web font.
// Run once after a font change: node src/tools/brand-glyphs.mjs (then npm run assets).
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as hb from 'harfbuzzjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const nm = path.join(root, 'node_modules');
const fontverter = createRequire(import.meta.url)('fontverter');

// Wordmark: weight 800, a mid optical size (the approved drafts were set at 22 to 42 px).
const WORD = { file: '@fontsource-variable/bricolage-grotesque/files/bricolage-grotesque-latin-opsz-normal.woff2', axes: { wght: 800, opsz: 36 }, tracking: -0.03 };
const TAG = { file: '@fontsource/eb-garamond/files/eb-garamond-latin-500-italic.woff2' };
// The first two letters of each word carry the colour of its ball (0 pink, 1 blue, 2 pistachio).
const TAGLINES = { de: 'Logik, Lösung, Live.', en: 'Logic, Loop, Live.' };

async function load({ file, axes }) {
  const ttf = await fontverter.convert(await readFile(path.join(nm, file)), 'truetype');
  const face = new hb.Face(new hb.Blob(ttf));
  const font = new hb.Font(face);
  if (axes) font.setVariations(Object.entries(axes).map(([tag, v]) => new hb.Variation(tag, v)));
  return { face, font };
}

// HarfBuzz paths are y-up in font units; SVG wants y-down. Coordinates are rounded to whole units (1/1000 em).
function flip(d) {
  const out = [];
  for (const [, cmd, args] of d.matchAll(/([MLQCZ])([^MLQCZ]*)/g)) {
    const n = (args.match(/-?\d*\.?\d+(?:e-?\d+)?/g) || []).map(Number);
    out.push([cmd, n.map((v, i) => Math.round(i % 2 ? -v : v))]);
  }
  return out;
}

// Contours as [cmd, coords] lists, with their bounding boxes (for the i's dot).
function contours(cmds) {
  const list = [];
  for (const c of cmds) {
    if (c[0] === 'M') list.push([]);
    list.at(-1).push(c);
  }
  return list.map((cs) => {
    const xs = cs.flatMap(([, n]) => n.filter((_, i) => i % 2 === 0));
    const ys = cs.flatMap(([, n]) => n.filter((_, i) => i % 2 === 1));
    return { cmds: cs, box: [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)] };
  });
}

function shape(font, text) {
  const buf = new hb.Buffer();
  buf.addText(text);
  buf.guessSegmentProperties();
  hb.shape(font, buf);
  return buf.getGlyphInfosAndPositions();
}

const word = await load(WORD);
const upem = word.face.upem;
const ext = word.font.hExtents();
const glyphs = {};
const layout = [];
let x = 0;
const text = 'mrlololı'; // dotless i: the dot is drawn as the pistachio ball
const shaped = shape(word.font, text);
shaped.forEach((g, i) => {
  const ch = text[g.cluster];
  glyphs[ch] ||= flip(word.font.glyphToPath(g.codepoint));
  layout.push([ch, x + (g.xOffset || 0)]);
  x += g.xAdvance + (i < shaped.length - 1 ? Math.round(WORD.tracking * upem) : 0);
});
// Where a real «i» has its dot: the top contour of the i glyph, at the ı's position.
const iGlyph = shape(word.font, 'i')[0];
const dot = contours(flip(word.font.glyphToPath(iGlyph.codepoint))).sort((a, b) => a.box[1] - b.box[1])[0].box;
const ink = contours(Object.values(glyphs).flat());

const tag = await load(TAG);
const taglines = {};
for (const [lang, line] of Object.entries(TAGLINES)) {
  const tg = {};
  const items = [];
  let tx = 0;
  // Character index -> ball colour for the first two letters of each word.
  const colour = new Map();
  let w = 0;
  for (const m of line.matchAll(/\p{L}+/gu)) { colour.set(m.index, w); colour.set(m.index + 1, w); w += 1; }
  for (const g of shape(tag.font, line)) {
    const key = String(g.codepoint);
    const d = tag.font.glyphToPath(g.codepoint);
    if (d) {
      tg[key] ||= flip(d);
      items.push([key, tx + (g.xOffset || 0), colour.has(g.cluster) ? colour.get(g.cluster) : -1]);
    }
    tx += g.xAdvance;
  }
  taglines[lang] = { text: line, glyphs: tg, layout: items, advance: tx };
}
const tagExt = tag.font.hExtents();

const json = {
  note: 'Generated by src/tools/brand-glyphs.mjs from the self-hosted fonts. Font units (1000 per em), y down, baseline at 0.',
  word: {
    font: 'Bricolage Grotesque', axes: WORD.axes, tracking: WORD.tracking, upem,
    ascender: ext.ascender, descender: ext.descender,
    glyphs, layout, advance: x,
    top: Math.min(...ink.map((c) => c.box[1])),
    dot: { cx: Math.round((dot[0] + dot[2]) / 2) + layout.at(-1)[1], cy: Math.round((dot[1] + dot[3]) / 2), size: dot[2] - dot[0] },
  },
  tagline: { font: 'EB Garamond italic 500', ascender: tagExt.ascender, descender: tagExt.descender, ...taglines },
};
await writeFile(path.join(root, 'src/templates/brand-glyphs.json'), `${JSON.stringify(json)}\n`);
console.log(`brand glyphs: wordmark ${x} units wide, dot ${JSON.stringify(json.word.dot)}, ascender ${ext.ascender}, descender ${ext.descender}, ink top ${json.word.top}`);
for (const [lang, t] of Object.entries(taglines)) console.log(`brand glyphs: tagline ${lang} «${t.text}» ${t.advance} units`);
